import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const sources = {
  projectDesign: 'common/schemas/project-design.schema.json',
  changeDesign: 'common/schemas/change-design.schema.json',
  browserEvidence: 'common/schemas/prototype-browser-evidence.schema.json',
  designPackage: 'specdev-p-prototype/assets/design-package.schema.json',
  designCatalog: 'specdev-p-prototype/design-library/catalog.schema.json',
};
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
const exports = {};
for (const [name, path] of Object.entries(sources)) {
  const schema = JSON.parse(await readFile(resolve(root, 'template/workflows/specdev', path), 'utf8'));
  ajv.addSchema(schema);
  exports[name] = schema.$id;
}
const result = await build({
  stdin: { contents: standalone(ajv, exports), resolveDir: root, sourcefile: 'design-validators.generated.js' },
  bundle: true, platform: 'node', target: 'node22', format: 'esm', write: false,
  legalComments: 'inline',
  banner: { js: '// Generated by scripts/generate-design-validators.mjs from design JSON schemas. Do not edit.' },
});
const target = resolve(root, 'template/lib/design-validators.mjs');
const output = result.outputFiles[0].text;
// Frozen historical evidence keeps its original schema. Ship a synchronous
// standalone validator so the read-only runtime needs no Ajv installation.
const legacyAjv = new Ajv2020({ allErrors: true, strict: true, strictTypes: false, code: { source: true } });
const legacySchema = JSON.parse(await readFile(resolve(root, 'template/workflows/specdev/common/schemas/change-status.schema.json'), 'utf8'));
const legacyValidator = legacyAjv.compile(legacySchema);
const legacyBuild = await build({ stdin: { contents: standalone(legacyAjv, legacyValidator), resolveDir: root, sourcefile: 'legacy-status-validator.generated.cjs' }, bundle: true, platform: 'node', target: 'node22', format: 'cjs', write: false, legalComments: 'inline', banner: { js: '// Generated from the frozen SpecDev change-status v6 schema. Do not edit.' } });
const legacyTarget = resolve(root, 'template/lib/legacy-status-validator.cjs');
const legacyOutput = legacyBuild.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if (await readFile(target, 'utf8').catch(() => '') !== output) throw new Error('design validators are stale; run pnpm generate-design-validators');
  if (await readFile(legacyTarget, 'utf8').catch(() => '') !== legacyOutput) throw new Error('legacy status validator is stale; run pnpm generate-design-validators');
  console.log('design schema validators: current');
} else {
  await writeFile(target, output);
  await writeFile(legacyTarget, legacyOutput);
  console.log('generated standalone design schema validators');
}
