import { build } from 'esbuild';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const output='template/lib/speculo-runtime.mjs';
const result=await build({entryPoints:['src/runtime-entry.ts'],bundle:true,platform:'node',target:'node22',format:'esm',write:false,legalComments:'inline',banner:{js:'// Generated by scripts/generate-runtime.mjs. Edit src/runtime-entry.ts and its dependencies.\nimport { createRequire as speculoCreateRequire } from "node:module"; const require = speculoCreateRequire(import.meta.url);'}});
const next=Buffer.from(result.outputFiles[0].contents);
if(process.argv.includes('--check')){
 const current=await readFile(output).catch(()=>null);
 if(!current?.equals(next)){console.error(`${output}: generated runtime is stale`);process.exitCode=1;}
}else{await mkdir('template/lib',{recursive:true});await writeFile(output,next);}
