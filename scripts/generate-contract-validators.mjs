import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standalone from 'ajv/dist/standalone/index.js';
import { build } from 'esbuild';

const root = resolve(import.meta.dirname, '..');
const sources = {
  projectDesign: 'common/schemas/project-design.schema.json',
  changeDesign: 'common/schemas/change-design.schema.json',
  browserEvidence: 'common/schemas/prototype-browser-evidence.schema.json',
  designPackage: 'specdev-p-prototype/assets/design-package.schema.json',
  designCatalog: 'specdev-p-prototype/design-library/catalog.schema.json',
};
const ajv = new Ajv2020({ allErrors: true, strict: true, code: { source: true, esm: true } });
addFormats(ajv);
const exports = {};
for (const [name, path] of Object.entries(sources)) {
  const schema = JSON.parse(await readFile(resolve(root, 'template/workflows/specdev', path), 'utf8'));
  ajv.addSchema(schema);
  exports[name] = schema.$id;
}
const result = await build({
  stdin: { contents: standalone(ajv, exports), resolveDir: root, sourcefile: 'design-validators.generated.js' },
  bundle: true, platform: 'node', target: 'node22', format: 'esm', write: false,
  legalComments: 'inline',
  banner: { js: '// Generated by scripts/generate-contract-validators.mjs from current design JSON schemas. Do not edit.' },
});
const target = resolve(root, 'template/lib/design-validators.mjs');
const output = result.outputFiles[0].text;
// Shared data contracts are schema-compiled once for CLI and portable runtime.
const contractAjv = new Ajv2020({ allErrors: true, strict: true, code: { source: true } });
addFormats(contractAjv);
const contractExports = {};
for (const [name, path] of Object.entries({
  workflowManifest: 'template/workflows/workflow-manifest.schema.json',
  capabilityProfile: 'template/references/contracts/capability-profile.schema.json',
})) {
  const schema = JSON.parse(await readFile(resolve(root, path), 'utf8'));
  contractAjv.addSchema(schema); contractExports[name] = schema.$id;
}
const contractBuild = await build({
  stdin: { contents: standalone(contractAjv, contractExports), resolveDir: root, sourcefile: 'contract-validators.generated.cjs' },
  bundle: true, platform: 'node', target: 'node22', format: 'cjs', write: false, legalComments: 'inline',
  banner: { js: '// Generated by scripts/generate-contract-validators.mjs from current shared schemas. Do not edit.' },
});
const outputs = new Map([[target, output], [resolve(root, 'template/lib/contract-validators.cjs'), contractBuild.outputFiles[0].text]]);
for (const [path, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (await readFile(path, 'utf8').catch(() => '') !== content) throw new Error(`${path}: stale; run pnpm generate-contract-validators`);
  } else await writeFile(path, content);
}
console.log(process.argv.includes('--check') ? 'current schema validators: current' : 'generated standalone current schema validators');
